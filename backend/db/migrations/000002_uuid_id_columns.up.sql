-- Legacy session IDs are opaque non-UUID tokens. Invalidate active sessions and OTP flows
-- before converting their primary keys to UUID.
DELETE FROM LOGIN_SESSION;
DELETE FROM OTP_SESSION;

ALTER TABLE TASK DROP CONSTRAINT IF EXISTS task_user_id_fkey;
ALTER TABLE LOGIN_SESSION DROP CONSTRAINT IF EXISTS login_session_user_id_fkey;
ALTER TABLE OTP_SESSION DROP CONSTRAINT IF EXISTS otp_session_user_id_fkey;

ALTER TABLE LOGIN_ACCOUNT ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE TASK ALTER COLUMN TASK_ID TYPE UUID USING TASK_ID::UUID;
ALTER TABLE TASK ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE LOGIN_SESSION ALTER COLUMN SESSION_ID TYPE UUID USING SESSION_ID::UUID;
ALTER TABLE LOGIN_SESSION ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE OTP_SESSION ALTER COLUMN OTP_SESSION_ID TYPE UUID USING OTP_SESSION_ID::UUID;
ALTER TABLE OTP_SESSION ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE LOGIN_LOG ALTER COLUMN LOG_ID TYPE UUID USING LOG_ID::UUID;
ALTER TABLE LOGIN_LOG ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE ACCESS_LOG ALTER COLUMN LOG_ID TYPE UUID USING LOG_ID::UUID;
ALTER TABLE ACCESS_LOG ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE MAIL_AUTH_LOG ALTER COLUMN LOG_ID TYPE UUID USING LOG_ID::UUID;
ALTER TABLE MAIL_AUTH_LOG ALTER COLUMN USER_ID TYPE UUID USING USER_ID::UUID;

ALTER TABLE TASK ADD CONSTRAINT task_user_id_fkey FOREIGN KEY (USER_ID) REFERENCES LOGIN_ACCOUNT(USER_ID) ON DELETE CASCADE;
ALTER TABLE LOGIN_SESSION ADD CONSTRAINT login_session_user_id_fkey FOREIGN KEY (USER_ID) REFERENCES LOGIN_ACCOUNT(USER_ID) ON DELETE CASCADE;
ALTER TABLE OTP_SESSION ADD CONSTRAINT otp_session_user_id_fkey FOREIGN KEY (USER_ID) REFERENCES LOGIN_ACCOUNT(USER_ID) ON DELETE CASCADE;
